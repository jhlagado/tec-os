#!/usr/bin/env node
// Build the TEC-OS ROM images with ATOM.
//
// For each hardware profile: generate the configuration and format equates,
// assemble once to measure the resident workspace, place TPATOP as high as
// that workspace allows, assemble again, check every placement rule and write
// the image, debug map and memory census to build/<profile>/.

import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assembleAtomProject, materializeAtomGeneration, writeAtomD8 } from "atom-z80";
import { format, geometryInfo } from "./lib/format.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(ROOT, "src");
const GEN = resolve(SRC, "gen");
const ROM_START = 0xc000;
const ROM_SIZE = 0x4000;
const CPU_HZ = 4_000_000;
const BAUD = 4800;
const VERSION = { major: 0, minor: 1 };

export const PROFILES = {
  debug80: { id: 1, nbanks: 9, tmsCols: 40, description: "Debug80 TEC-1G model: nine expansion banks, TMS9918 40 columns" },
  debug80g32: { id: 3, nbanks: 9, tmsCols: 32, description: "Debug80 TEC-1G model: nine expansion banks, TMS9918 32 columns" },
  board: { id: 2, nbanks: 1, tmsCols: 40, description: "TEC-1G as documented: one upper U9 half, TMS9918 40 columns" },
};

const hex = (value, width = 4) => `$${value.toString(16).toUpperCase().padStart(width, "0")}`;

/** Delay-loop counts for the bit-banged serial routines in console.asm. */
function serialTiming() {
  const bit = CPU_HZ / BAUD;
  const txdly = Math.round((bit - 49) / 16); // TXB loop: 49 + 16n T-states
  const rxdly = Math.round((bit - 38) / 16); // RXB loop: 38 + 16n
  const kbLate = 280; // longest gap between start-bit polls: one keyboard row scan
  const rxhalf = Math.round((1.5 * bit - 51 - kbLate / 2) / 16); // edge to the middle of bit 0
  const txstop = Math.round((2 * bit) / 16) + 1;
  const rxpoll = Math.ceil((3.5 * bit) / 38); // CSTPOLL loop: 38 T-states
  for (const [name, n] of Object.entries({ txdly, rxdly, rxhalf, txstop, rxpoll })) {
    if (n < 1 || n > 255) throw new Error(`serial delay ${name}=${n} does not fit a byte`);
  }
  return {
    txdly,
    rxdly,
    rxhalf,
    txstop,
    rxpoll,
    txBitCycles: 49 + 16 * txdly,
    rxBitCycles: 38 + 16 * rxdly,
    bitCycles: bit,
  };
}

function writeGenerated(profile, tpatop) {
  mkdirSync(GEN, { recursive: true });
  const s = serialTiming();
  writeFileSync(
    resolve(GEN, "config.asm"),
    `; Generated by tools/build.mjs for profile ${profile.name}. Do not edit.
PROFILE EQU     ${profile.id}
NBANKS  EQU     ${profile.nbanks}
TPATOP  EQU     ${hex(tpatop)}
VERHI   EQU     ${VERSION.major}
VERLO   EQU     ${VERSION.minor}
ROMVER  EQU     ${hex((VERSION.major << 8) | VERSION.minor)}
TXDLY   EQU     ${s.txdly}
TXSTOP  EQU     ${s.txstop}
RXDLY   EQU     ${s.rxdly}
RXHALF  EQU     ${s.rxhalf}
RXPOLL  EQU     ${s.rxpoll}
TMSCOLS EQU     ${profile.tmsCols}
`,
  );
  const h = format.header.fields;
  const d = format.descriptor.fields;
  writeFileSync(
    resolve(GEN, "format.asm"),
    `; Generated from format/format.json. Do not edit.
FMTMAJ  EQU     ${format.formatVersion.major}
HDRSZ   EQU     ${format.header.bytes}
DSCSZ   EQU     ${format.descriptor.bytes}
MAXVOL  EQU     ${format.header.maxVolumes}
HMAJOR  EQU     ${h.major.offset}
HHDRSZ  EQU     ${h.headerBytes.offset}
HDSCSZ  EQU     ${h.descriptorBytes.offset}
HCOUNT  EQU     ${h.volumeCount.offset}
HBLOCKS EQU     ${h.containerBlocks.offset}
HCKSUM  EQU     ${h.checksum.offset}
HDESC   EQU     ${format.header.descriptorsOffset}
DVOLID  EQU     ${d.volumeId.offset}
DSTART  EQU     ${d.startBlock.offset}
DLEN    EQU     ${d.lengthBlocks.offset}
DGEOM   EQU     ${d.geometry.offset}
DFLAGS  EQU     ${d.flags.offset}
DMOUNT  EQU     ${d.mount.offset}
DLABEL  EQU     ${d.label.offset}
DFREAD  EQU     ${format.descriptor.flags.readOnly}
DUNMNT  EQU     ${format.descriptor.unmounted}
ALIGNB  EQU     ${format.descriptor.startAlignBlocks}
GEOCNT  EQU     ${format.geometries.length}
GEOESZ  EQU     6
`,
  );
  const lines = [
    "; Generated from format/format.json. Do not edit.",
    `FMTMAG: DB      "${format.header.magic}"`,
    "; Geometry table: id, 0, payload blocks, DPB address.",
    "GEOTAB:",
  ];
  for (const g of format.geometries) {
    lines.push(`        DB      ${g.id},0`, `        DW      ${g.payloadBlocks},DPB${g.id}`);
  }
  for (const g of format.geometries) {
    const p = geometryInfo(g).dpb;
    lines.push(
      `; ${g.name}: ${g.description}`,
      `DPB${g.id}:   DW      ${p.spt}`,
      `        DB      ${p.bsh},${p.blm},${p.exm}`,
      `        DW      ${p.dsm},${p.drm}`,
      `        DB      ${p.al0},${p.al1}`,
      `        DW      ${p.cks},${p.off}`,
    );
  }
  writeFileSync(resolve(GEN, "geom.asm"), lines.join("\n") + "\n");
  writeFileSync(resolve(GEN, "font.asm"), fontSource());
  return s;
}

/** The console font from format/font5x7.txt as DB rows, 96 glyphs. */
function fontSource() {
  const text = readFileSync(resolve(ROOT, "format/font5x7.txt"), "utf8");
  const glyphs = new Map();
  let code;
  let rows;
  for (const line of text.split(/\r?\n/)) {
    if (line.trim() === "" || (line.startsWith("#") && !/^[#.]{5}$/.test(line))) continue;
    const head = /^= ([0-9A-F]{2})$/.exec(line);
    if (head) {
      code = parseInt(head[1], 16);
      rows = [];
      glyphs.set(code, rows);
      continue;
    }
    if (!/^[#.]{5}$/.test(line)) throw new Error(`font: bad row ${JSON.stringify(line)}`);
    rows.push(parseInt(line.replace(/#/g, "1").replace(/\./g, "0"), 2) << 3);
  }
  const out = ["; Generated from format/font5x7.txt. Do not edit.", "FONT:"];
  for (let c = 0x20; c < 0x80; c += 1) {
    const g = glyphs.get(c);
    if (!g || g.length !== 8) throw new Error(`font: glyph ${c.toString(16)} missing or not 8 rows`);
    out.push(`        DB      ${g.map((v) => "$" + v.toString(16).toUpperCase().padStart(2, "0")).join(",")}`);
  }
  return out.join("\n") + "\n";
}

let currentDefinitions = {};

async function assemble() {
  const result = await assembleAtomProject({ root: SRC, entry: "rom.asm", definitions: currentDefinitions });
  const d8 = writeAtomD8(result.project, result.generation, { base: ROM_START });
  const symbols = new Map();
  for (const symbol of d8.symbols) symbols.set(symbol.name, symbol.address ?? symbol.value);
  return { result, d8, symbols };
}

function need(symbols, name) {
  const value = symbols.get(name);
  if (typeof value !== "number") throw new Error(`symbol ${name} missing from the map`);
  return value;
}

function check(condition, message) {
  if (!condition) throw new Error(`placement check failed: ${message}`);
}

// The resident workspace does not depend on the profile, so one probe
// assembly sizes it for every profile.
let workspaceBytes;

async function buildProfile(name) {
  const profile = { name, ...PROFILES[name] };
  currentDefinitions = { TMS32: profile.tmsCols === 32 ? 1 : 0 };
  if (workspaceBytes === undefined) {
    writeGenerated(profile, 0x8000);
    const probe = await assemble();
    workspaceBytes = need(probe.symbols, "WSEND") - 0x8000;
  }
  const workspace = workspaceBytes;
  const tpatop = (0xc000 - workspace) & 0xff00;
  const serial = writeGenerated(profile, tpatop);
  const { result, d8, symbols } = await assemble();

  for (const image of result.generation.images) {
    check(image.address >= ROM_START, `ROM byte emitted at ${hex(image.address)}`);
  }
  const { bytes } = materializeAtomGeneration(result.generation, { base: ROM_START, fill: 0xff });
  check(bytes.length <= ROM_SIZE, `image is ${bytes.length} bytes`);
  const rom = new Uint8Array(ROM_SIZE).fill(0xff);
  rom.set(bytes);

  const at = (n) => need(symbols, n);
  check(at("RESET") === 0xc000, "RESET must be at C000h");
  check(at("INT38") === 0xc038, "INT38 must be at C038h");
  check(at("NMIROM") === 0xc066, "NMIROM must be at C066h");
  check(at("COLD") < 0xc800, "cold boot entry must be inside the overlay window");
  check(at("CODEEND") <= at("ABITAB"), "code overruns the native ABI table at FF00h");
  check(at("ABITAB") === 0xff00, "ABI table must be at FF00h");
  check(at("WSBASE") === tpatop + 0x100 + 51, "workspace starts after the RAM BIOS table");
  check(at("WSEND") <= 0xc000, `workspace ends at ${hex(at("WSEND"))}`);
  check(at("RAMBIOS") % 256 === 0, "RAM BIOS table must be page aligned");
  check((at("BENTRY") - at("BDOSBAS")) === 6, "BDOS entry is six bytes into the BDOS");
  check(at("BSTK") <= at("CCPRAM"), "BIOS stack overlaps the CCP workspace");

  const outDir = resolve(ROOT, "build", name);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, "tecos.rom"), rom);
  writeFileSync(resolve(outDir, "tecos.d8.json"), JSON.stringify(d8, null, 2));

  const census = {
    profile: name,
    description: profile.description,
    nbanks: profile.nbanks,
    sha256: createHash("sha256").update(rom).digest("hex"),
    serial,
    rom: {
      bytes: ROM_SIZE,
      used: at("CODEEND") - ROM_START + (at("ABIEND") - at("ABITAB")),
      free: at("ABITAB") - at("CODEEND") + (0x10000 - at("ABIEND")),
      regions: [
        ["vectors and boot", at("RESET"), at("BIOSBAS")],
        ["BIOS", at("BIOSBAS"), at("CONINIT")],
        ["console", at("CONINIT"), at("SPIW")],
        ["SD driver", at("SPIW"), at("MOUNT")],
        ["volume mount", at("MOUNT"), at("FMTMAG")],
        ["format tables", at("FMTMAG"), at("DIAG")],
        ["diagnostics", at("DIAG"), at("CCPBAS")],
        ["CCP", at("CCPBAS"), at("CCPROM")],
        ["BDOS", at("BDOSBAS"), at("BDOSROM")],
        ["native ABI", at("SETBANK"), at("CODEEND")],
        ["ABI table", at("ABITAB"), at("ABIEND")],
      ].map(([label, start, end]) => ({ label, start, end, bytes: end - start })),
    },
    ram: {
      tpa: { start: 0x0100, end: tpatop + 6, bytes: tpatop + 6 - 0x100 },
      stubPage: tpatop,
      bdosVector: tpatop + 6,
      ramBios: at("RAMBIOS"),
      regions: [
        ["stub page", tpatop, tpatop + 0x100],
        ["RAM BIOS table", at("RAMBIOS"), at("WSBASE")],
        ["BIOS disk state and buffers", at("WSBASE"), at("SDBYTE")],
        ["SD and mount state", at("SDBYTE"), at("BSTKB")],
        ["BIOS stack", at("BSTKB"), at("BSTK")],
        ["CCP state and stack", at("CCPRAM"), at("CCPRME")],
        ["BDOS state and stack", at("BDOSRAM"), at("BDOSRME")],
        ["unused", at("WSEND"), 0xc000],
      ].map(([label, start, end]) => ({ label, start, end, bytes: end - start })),
      stacks: {
        boot: { top: 0x8000 },
        bios: { base: at("BSTKB"), top: at("BSTK"), bytes: at("BSTK") - at("BSTKB") },
        ccp: { base: at("CSTKBAS"), top: at("CSTKTOP"), bytes: at("CSTKTOP") - at("CSTKBAS") },
        bdos: { base: at("STKBASE"), top: at("STKTOP"), bytes: at("STKTOP") - at("STKBASE") },
      },
    },
  };
  writeFileSync(resolve(outDir, "census.json"), JSON.stringify(census, null, 2) + "\n");
  return census;
}

export async function build(names = Object.keys(PROFILES)) {
  const out = [];
  for (const name of names) out.push(await buildProfile(name));
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = process.argv.slice(2);
  try {
    for (const census of await build(names.length ? names : undefined)) {
      console.log(
        `${census.profile}: ROM ${census.rom.used}/${census.rom.bytes} bytes, ` +
          `TPA ${hex(census.ram.tpa.start)}-${hex(census.ram.tpa.end - 1)} (${census.ram.tpa.bytes} bytes), ` +
          `sha256 ${census.sha256.slice(0, 16)}`,
      );
    }
  } catch (error) {
    console.error(error.diagnostic ? JSON.stringify(error.diagnostic) : "", error.message);
    process.exit(1);
  }
}
