#!/usr/bin/env node
// Build the TEC-OS ROM images with ATOM.
//
// For each hardware profile: generate the configuration and format equates,
// assemble once to measure the resident workspace, place TPATOP as high as
// that workspace allows, assemble again, check every placement rule and write
// the image, debug map and memory census to build/<profile>/, and to dist/ when
// npm run media has made it.

import { copyFileSync, existsSync, mkdirSync, readdirSync, writeFileSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assembleAtomProject, materializeAtomGeneration, writeAtomD8 } from "atom-z80";
import { format, geometryInfo } from "./lib/format.mjs";
import { FORMAT, checkInterfaces, makeSvc } from "./lib/svc.mjs";
import { romFontSource } from "./lib/font.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(ROOT, "src");
const GEN = resolve(SRC, "gen");
const ROM_START = 0xc000;
const ROM_SIZE = 0x4000;
const RAMBIOS = 0xbf00; // src/layout.asm; the workspace below it sets TPATOP
const CPU_HZ = 4_000_000;
const BAUD = 4800;
const VERSION = { major: 0, minor: 1 };

// One image, one name, for every board: the display's width is a driver.
export const PROFILES = {
  tecos: { description: "the TEC-1G, on the board and in Debug80" },
};

const hex = (value, width = 4) => `$${value.toString(16).toUpperCase().padStart(width, "0")}`;

/** Delay-loop counts for the bit-banged serial routines in console.asm. */
function serialTiming() {
  const bit = CPU_HZ / BAUD;
  const txdly = Math.round((bit - 49) / 16); // TXB loop: 49 + 16n T-states
  const rxdly = Math.round((bit - 38) / 16); // RXB loop: 38 + 16n
  const kbLate = 38; // longest gap between start-bit polls in the serial loops
  // Edge to the middle of bit 0, with RXBITS's mask: 65 or 52 T-states before RXH.
  const rxhalf = Math.round((1.5 * bit - 51 - 58.5 - kbLate / 2) / 16);
  const txstop = Math.round((2 * bit) / 16) + 1;
  const rxpoll = Math.ceil((3.5 * bit) / 38); // CSTPOLL loop: 38 T-states
  for (const [name, n] of Object.entries({ txdly, rxdly, rxhalf, txstop, rxpoll })) {
    if (n < 1 || n > 255) throw new Error(`serial delay ${name}=${n} does not fit a byte`);
  }
  return {
    txdly,
    rxdly,
    rxhalf,
    txstop,
    rxpoll,
    txBitCycles: 49 + 16 * txdly,
    rxBitCycles: 38 + 16 * rxdly,
    bitCycles: bit,
  };
}

function writeGenerated(profile, wsbase) {
  mkdirSync(GEN, { recursive: true });
  const s = serialTiming();
  writeFileSync(
    resolve(GEN, "config.asm"),
    `; Generated by tools/build.mjs for profile ${profile.name}. Do not edit.
WSBASE  EQU     ${hex(wsbase)}
VERHI   EQU     ${VERSION.major}
VERLO   EQU     ${VERSION.minor}
ROMVER  EQU     ${hex((VERSION.major << 8) | VERSION.minor)}
TXDLY   EQU     ${s.txdly}
TXSTOP  EQU     ${s.txstop}
RXDLY   EQU     ${s.rxdly}
RXHALF  EQU     ${s.rxhalf}
RXPOLL  EQU     ${s.rxpoll}
`,
  );
  const h = format.header.fields;
  const d = format.descriptor.fields;
  writeFileSync(
    resolve(GEN, "format.asm"),
    `; Generated from format/format.json. Do not edit.
FMTMAJ  EQU     ${format.formatVersion.major}
HDRSZ   EQU     ${format.header.bytes}
DSCSZ   EQU     ${format.descriptor.bytes}
MAXVOL  EQU     ${format.header.maxVolumes}
MAXVOL0 EQU     ${format.header.maxVolumesMinor0}
DSCBLK0 EQU     ${format.header.descriptorsInBlock0}
HMAJOR  EQU     ${h.major.offset}
HMINOR  EQU     ${h.minor.offset}
HDRIVES EQU     ${h.drives.offset}
HTSUM   EQU     ${h.tableSum.offset}
HHDRSZ  EQU     ${h.headerBytes.offset}
HDSCSZ  EQU     ${h.descriptorBytes.offset}
HCOUNT  EQU     ${h.volumeCount.offset}
HBLOCKS EQU     ${h.containerBlocks.offset}
HCKSUM  EQU     ${h.checksum.offset}
HDESC   EQU     ${format.header.descriptorsOffset}
DVOLID  EQU     ${d.volumeId.offset}
DSTART  EQU     ${d.startBlock.offset}
DLEN    EQU     ${d.lengthBlocks.offset}
DGEOM   EQU     ${d.geometry.offset}
DFLAGS  EQU     ${d.flags.offset}
DMOUNT  EQU     ${d.mount.offset}
DLABEL  EQU     ${d.label.offset}
DCACHE  EQU     ${d.cache.offset}
DCWB    EQU     ${format.descriptor.cacheFlags.writeBehind}
DFREAD  EQU     ${format.descriptor.flags.readOnly}
DUNMNT  EQU     ${format.descriptor.unmounted}
ALIGNB  EQU     ${format.descriptor.startAlignBlocks}
GEOCNT  EQU     ${format.geometries.length}
GEOESZ  EQU     6
`,
  );
  const lines = [
    "; Generated from format/format.json. Do not edit.",
    `FMTMAG: DB      "${format.header.magic}"`,
    "; Geometry table: id, 0, payload blocks, DPB address.",
    "GEOTAB:",
  ];
  for (const g of format.geometries) {
    lines.push(`        DB      ${g.id},0`, `        DW      ${g.payloadBlocks},DPB${g.id}`);
  }
  for (const g of format.geometries) {
    const p = geometryInfo(g).dpb;
    lines.push(
      `; ${g.name}: ${g.description}`,
      `DPB${g.id}:   DW      ${p.spt}`,
      `        DB      ${p.bsh},${p.blm},${p.exm}`,
      `        DW      ${p.dsm},${p.drm}`,
      `        DB      ${p.al0},${p.al1}`,
      `        DW      ${p.cks},${p.off}`,
    );
  }
  writeFileSync(resolve(GEN, "geom.asm"), lines.join("\n") + "\n");
  // The ROM's copy of the font, service 15's (KS36c), in the data block.
  writeFileSync(resolve(GEN, "font.asm"), romFontSource(ROOT));
  return s;
}

let currentDefinitions = {};

/** ABI 5's table as the ROM holds it: "TNA", the major, the minor, then JP to
 *  the dispatcher, 8 bytes at abi.inc's addresses, which the ROM includes; the
 *  service table one word a number; INFO's bits CONDEV's. */
function checkAbi(at, rom) {
  const byte = (a) => rom[a - 0xc000];
  check(String.fromCharCode(byte(at("ABITAB")), byte(at("ABITAB") + 1), byte(at("ABITAB") + 2)) === "TNA", "the signature at ABITAB");
  check(byte(at("ABIMAJ")) === 5 && byte(at("ABIMIN")) === 1, "ABI 5.1 at ABIMAJ and ABIMIN");
  check(byte(at("ABICALL")) === 0xc3 && (byte(at("ABICALL") + 1) | (byte(at("ABICALL") + 2) << 8)) === at("SVCDSP"), "ABICALL is JP SVCDSP");
  check(at("ABIEND") === at("ABICALL") + 3 && at("ABIEND") - at("ABITAB") === 8, "the table is 8 bytes");
  check(at("SVCFMT") === FORMAT, `abi.inc's SVCFMT is ${at("SVCFMT")}, tools/lib/svc-format.mjs has ${FORMAT}`);
  const table = Array.from({ length: at("TNCOUNT") }, (_, n) => byte(at("SVTAB") + 2 * n) | (byte(at("SVTAB") + 2 * n + 1) << 8));
  check(table.every((v) => v >= at("ROMCODE") && v < at("CODEEND")), "every service's entry is code");
  const bits = { HWBMTX: "CDMTX", HWBPICO: "CDTMS", HWBGLCD: "CDGLC", HWBRTC: "CDRTC", HWBCLM: "CDCLM", HWBWRD: "CDWRD" };
  for (const [n, cd] of Object.entries(bits)) check(at(n) === at(cd), `abi.inc: ${n} is not ${cd}`);
}

/** abi.inc's PICOREG to PICOWID, and the places a debugger reads, against the
 *  ROM's console (KS39): each entry is the word at its offset in PITPL, the
 *  template PIBLK is filled from, and each place lies at its offset in PIBLK. */
function checkPicoTable(at, rom) {
  const byte = (a) => rom[a - 0xc000];
  const inc = readFileSync(resolve(SRC, "abi.inc"), "utf8");
  const offsets = new Map([...inc.matchAll(/^(PICO[A-Z]+)\s+EQU\s+(\d+)\b/gm)].map((m) => [m[1], Number(m[2])]));
  const entries = { PICOREG: "GFXREG", PICOFIL: "GFXFIL", PICOWR: "GFXWR", PICORD: "GFXRD", PICOWID: "TMSWID" };
  const places = { PICOVRB: "PIREC+10", PICOTPD: "PITPD", PICOTPS: "PITPS" };
  check(offsets.size === Object.keys(entries).length + Object.keys(places).length + 1 && offsets.has("PICOVER"), "abi.inc: the PICO table's offsets");
  const word = (a) => byte(a) | (byte(a + 1) << 8);
  check(byte(at("PITPL") + offsets.get("PICOVRB")) === offsets.get("PICOVER"), "abi.inc: the PICO record is not at PICOVER");
  for (const [n, label] of Object.entries(entries)) check(word(at("PITPL") + offsets.get(n)) === at(label), `abi.inc: ${n} is not ${label} in the PICO table`);
  for (const [n, place] of Object.entries(places)) {
    const [label, plus = 0] = place.split("+");
    check(at("PIBLK") + offsets.get(n) === at(label) + Number(plus), `abi.inc: ${n} is not ${place}`);
  }
}

/** A service's source reaches the ROM only through abi.inc's names. The build
 *  fails if it finds none, or if the demo in test/programs drops out. */
function checkServiceSources() {
  const checked = [];
  for (const dir of ["drivers", "test/programs"]) {
    for (const f of readdirSync(resolve(ROOT, dir)).filter((n) => n.endsWith(".asm") && (dir === "drivers" || n.startsWith("svc")))) {
      checkInterfaces(readFileSync(resolve(ROOT, dir, f), "utf8"), `${dir}/${f}`);
      checked.push(`${dir}/${f}`);
    }
  }
  check(checked.includes("drivers/glcd.asm") && checked.includes("test/programs/svcdemo.asm"), `the service sources checked were ${checked.join(", ") || "none"}`);
  return checked;
}

// The emulated assembler's budget: the ROM took about 1.99 billion cycles at
// 621201d, against atom-z80's default of 2 billion, so these give it headroom.
const ATOM_BUDGET = { maxCycles: 4_000_000_000, maxInstructions: 400_000_000 };

async function assemble() {
  const result = await assembleAtomProject({ root: SRC, entry: "rom.asm", definitions: currentDefinitions, ...ATOM_BUDGET });
  const d8 = writeAtomD8(result.project, result.generation, { base: ROM_START });
  const symbols = new Map();
  for (const symbol of d8.symbols) symbols.set(symbol.name, symbol.address ?? symbol.value);
  return { result, d8, symbols };
}

function need(symbols, name) {
  const value = symbols.get(name);
  if (typeof value !== "number") throw new Error(`symbol ${name} missing from the map`);
  return value;
}

function check(condition, message) {
  if (!condition) throw new Error(`placement check failed: ${message}`);
}

// The DSMs of the volumes on a card, by drive: the starter card (tools/media.mjs)
// and the largest card, four 8 MiB volumes.
const CARDS = { starter: [511, 2047], fourG8M: [2047, 2047, 2047, 2047] };

/** ALVINIT's layout for a card: vectors packed down from WSBASE, the BDOS
 *  entry jump directly below them. */
function cardLayout(wsbase, dsms) {
  const alvBase = wsbase - dsms.reduce((n, dsm) => n + (dsm >> 3) + 1, 0);
  const entry = alvBase - 3;
  return { entry, alvBase, tpa: entry - 0x100 };
}

// The resident workspace below the RAM BIOS table does not depend on the
// profile, so one probe assembly sizes it for every profile.
let workspaceBytes;

async function buildProfile(name) {
  const profile = { name, ...PROFILES[name] };
  if (workspaceBytes === undefined) {
    writeGenerated(profile, 0x8000);
    const probe = await assemble();
    workspaceBytes = need(probe.symbols, "BDOSRME") - 0x8000;
  }
  const wsbase = RAMBIOS - workspaceBytes;
  const serial = writeGenerated(profile, wsbase);
  const { result, d8, symbols } = await assemble();

  for (const image of result.generation.images) {
    check(image.address >= ROM_START, `ROM byte emitted at ${hex(image.address)}`);
  }
  const { bytes } = materializeAtomGeneration(result.generation, { base: ROM_START, fill: 0xff });
  check(bytes.length <= ROM_SIZE, `image is ${bytes.length} bytes`);
  const rom = new Uint8Array(ROM_SIZE).fill(0xff);
  rom.set(bytes);

  const at = (n) => need(symbols, n);
  check(at("RESET") === 0xc000, "RESET must be at C000h");
  check(at("ABITAB") === 0xc003, "the table must be at C003h");
  check(at("ABIEND") === at("ROMDATA"), "the data block must follow the table");
  check(at("ROMDATA") <= at("ROMCODE") && at("ROMCODE") <= at("CODEEND"), "the table, the data and the code, in that order");
  check(at("CODEEND") <= 0x10000, "the code overruns the ROM");
  checkAbi(at, rom);
  checkPicoTable(at, rom);
  checkServiceSources();
  check(at("RAMBIOS") === RAMBIOS, `RAM BIOS table must be at ${hex(RAMBIOS)}`);
  check(at("BDOSRME") === RAMBIOS, `the fixed workspace must end at the RAM BIOS table, not ${hex(at("BDOSRME"))}`);
  check(at("SDBYTE") === RAMBIOS + 51, "the state above the RAM BIOS table follows it");
  check(at("WSEND") <= 0xc000, `workspace ends at ${hex(at("WSEND"))}`);
  check(at("BSTK") <= at("CCPRAM"), "BIOS stack overlaps the CCP workspace");

  const starter = cardLayout(at("WSBASE"), CARDS.starter);
  check(starter.entry - 0x100 >= 45830, `the starter card's TPA is ${starter.entry - 0x100} bytes`);

  const outDir = resolve(ROOT, "build", name);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, "tecos.rom"), rom);
  writeFileSync(resolve(outDir, "tecos.d8.json"), JSON.stringify(d8, null, 2));

  const census = {
    profile: name,
    description: profile.description,
    sha256: createHash("sha256").update(rom).digest("hex"),
    serial,
    rom: {
      bytes: ROM_SIZE,
      used: at("CODEEND") - ROM_START,
      free: 0x10000 - at("CODEEND"),
      regions: [
        ["reset jump", at("RESET"), at("RESET") + 3],
        ["table", at("ABITAB"), at("ABIEND")],
        ["data", at("ROMDATA"), at("ROMCODE")],
        ["code", at("ROMCODE"), at("CODEEND")],
        ["free", at("CODEEND"), 0x10000],
      ].map(([label, start, end]) => ({ label, start, end, bytes: end - start })),
    },
    ram: {
      tpa: { start: 0x0100, end: starter.entry, bytes: starter.entry - 0x100, card: "starter" },
      bdosVector: starter.entry,
      cards: Object.fromEntries(Object.entries(CARDS).map(([k, dsms]) => [k, cardLayout(at("WSBASE"), dsms)])),
      fixedBase: at("WSBASE"),
      ramBios: at("RAMBIOS"),
      regions: [
        ["BDOS entry jump, starter card", starter.entry, starter.entry + 3],
        ["unused", starter.entry + 3, starter.alvBase],
        ["allocation vectors, starter card", starter.alvBase, at("WSBASE")],
        ["BIOS disk state and buffers", at("WSBASE"), at("BSTKB")],
        ["BIOS stack", at("BSTKB"), at("BSTK")],
        ["CCP state and stack", at("CCPRAM"), at("CCPRME")],
        ["BDOS state and stack", at("BDOSRAM"), at("BDOSRME")],
        ["RAM BIOS table", at("RAMBIOS"), at("SDBYTE")],
        ["SD, keyboard and GLCD state", at("SDBYTE"), at("WSEND")],
        ["unused", at("WSEND"), 0xc000],
      ].map(([label, start, end]) => ({ label, start, end, bytes: end - start })),
      stacks: {
        boot: { top: 0x8000 },
        bios: { base: at("BSTKB"), top: at("BSTK"), bytes: at("BSTK") - at("BSTKB") },
        ccp: { base: at("CSTKBAS"), top: at("CSTKTOP"), bytes: at("CSTKTOP") - at("CSTKBAS") },
        bdos: { base: at("STKBASE"), top: at("STKTOP"), bytes: at("STKTOP") - at("STKBASE") },
      },
    },
  };
  writeFileSync(resolve(outDir, "census.json"), JSON.stringify(census, null, 2) + "\n");
  refreshDist(outDir, census);
  return census;
}

/** A dist/ that npm run media made gets the new ROM, map and census, under
 *  the names media gives them, and the manifest's figures (KE-188): the rest of
 *  dist/, the card and its files, waits for npm run media. */
function refreshDist(outDir, census) {
  const dist = resolve(ROOT, "dist");
  if (!existsSync(dist)) return;
  copyFileSync(resolve(outDir, "tecos.rom"), resolve(dist, "tecos.rom"));
  copyFileSync(resolve(outDir, "tecos.d8.json"), resolve(dist, "tecos.d8.json"));
  copyFileSync(resolve(outDir, "census.json"), resolve(dist, "tecos.census.json"));
  const path = resolve(dist, "manifest.json");
  if (!existsSync(path)) return;
  const manifest = JSON.parse(readFileSync(path, "utf8"));
  manifest[census.profile] = { sha256: census.sha256, romUsed: census.rom.used, tpaBytes: census.ram.tpa.bytes };
  writeFileSync(path, JSON.stringify(manifest, null, 2) + "\n");
}

export async function build() {
  return [await buildProfile("tecos")];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = process.argv.slice(2);
  try {
    if (names.some((n) => n !== "tecos")) throw new Error(`one image, tecos: not ${names.join(" ")}`);
    for (const census of await build()) {
      console.log(
        `${census.profile}: ROM ${census.rom.used}/${census.rom.bytes} bytes, ` +
          `TPA ${hex(census.ram.tpa.start)}-${hex(census.ram.tpa.end - 1)} (${census.ram.tpa.bytes} bytes), ` +
          `sha256 ${census.sha256.slice(0, 16)}`,
      );
    }
  } catch (error) {
    console.error(error.diagnostic ? JSON.stringify(error.diagnostic) : "", error.message);
    process.exit(1);
  }
}
