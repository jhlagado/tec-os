// Development scenario generator and native launcher overlay builder.
// node tools/caverns-scenario.mjs build
// node tools/caverns-scenario.mjs write scenario.json NAME.CAV
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {tasAssembler} from './lib/tas-rom.mjs';
import {parseContainer,findVolume,volumePayload} from './lib/container.mjs';
import {CpmVolume} from './lib/cpmfs.mjs';
const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root));
const hash=b=>createHash('sha256').update(b).digest();
const basic=JSON.parse(read('test/caverns-basic.json'));
const game=read('programs/CAVBASIC.COM');
assert.equal(hash(game).toString('hex'),basic.comSha256,'launcher must match the qualified BASIC executable');
export const scalarNames=['A%','H%','D%','W%','G%','T%','E%','J%','C0%','F%','U%'];
export function encodeScenario(s){
 assert.equal(s.format,'caverns-basic-scenario-1');
 assert.equal(s.gameSha256,basic.comSha256);
 assert.equal(s.objects.length,24);
 const out=Buffer.alloc(128);Buffer.from('CVB1').copy(out);out[4]=1;hash(game).copy(out,8,0,8);
 const scalars=s.variables;
 const allowed={'A%':v=>v>=1&&v<=54,'H%':v=>v===11,'D%':v=>v===128||v===49,'W%':v=>v===0||v===43,'G%':v=>v===0||v===39,'T%':v=>v===0||v===19,'E%':v=>v===0||v===38,'J%':v=>v===0||v===1,'C0%':v=>v===0||v===1,'F%':v=>v>=0&&v<=32767,'U%':v=>v>=0&&v<=32767};
 s.objects.forEach((v,i)=>{assert.ok(Number.isInteger(v)&&v>=-1&&v<=255);if(i>=6)assert.ok(v<=54);out.writeInt16LE(v,16+2*i);});
 scalarNames.forEach((n,i)=>{const v=scalars[n];assert.ok(Number.isInteger(v)&&allowed[n](v),'invalid '+n);out.writeInt16LE(v,64+2*i);});
 assert.match(s.rng,/^[0-9a-fA-F]{8}$/);const rng=Number.parseInt(s.rng,16);assert.notEqual(rng,0);out.writeUInt32LE(rng,86);
 let sum=0;for(let i=0;i<128;i++)if(i!==6&&i!==7)sum+=out[i];out.writeUInt16LE(sum,6);return out;
}
export function layout(){
 function line(n){const found=[];for(let i=0;i<game.length-9;i++)if(game[i]===0x11&&game.readUInt16LE(i+1)===n&&game[i+3]===1&&game.readUInt16LE(i+4)===0&&game[i+6]===0xcd)found.push(i+256);assert.equal(found.length,1,'unique BASIC line '+n);return found[0];}
 const seeds=[];for(let i=0;i<game.length-12;i++)if(game[i]===0x21&&game.readUInt16LE(i+1)===0x1234&&game[i+3]===0x22&&game[i+6]===0x21&&game.readUInt16LE(i+7)===0x5a4a&&game[i+9]===0x22){assert.equal(game.readUInt16LE(i+10),game.readUInt16LE(i+4)+2);seeds.push(game.readUInt16LE(i+4));}
 assert.equal(seeds.length,1,'unique qualified runtime RNG initializer');
 return {entry:line(30),resume:line(50),rng:seeds[0]};
}
export async function buildLauncher(){
 const l=layout(),symbols={OBJECTS:basic.symbols['P%()'].address,RNG:l.rng,RESUME:l.resume};
 ['ROOM','BRIDGE','DRAWBR','WALL','GRILLE','DOOR','CRYPT','HUT','LIGHT','FATIGUE','MOVES'].forEach((n,i)=>symbols[n]=basic.symbols[scalarNames[i]].address);
 [...hash(game).subarray(0,8)].forEach((v,i)=>symbols['HASH'+i]=v);
 writeFileSync(new URL('programs/caverns/load.inc',root),'; Generated by tools/caverns-scenario.mjs; qualified COM-specific addresses.\n'+Object.entries(symbols).map(([n,v])=>n+' EQU $'+v.toString(16).toUpperCase()).join('\n')+'\n');
 const assemble=await tasAssembler(),a=await assemble({root:new URL('programs/caverns',root).pathname,entry:'load.asm',origin:l.entry,phase:'caverns-loader',target:'tecos'});
 assert.ok(a.end<=l.resume,`loader ${a.image.length} bytes exceeds ${l.resume-l.entry}-byte banner`);
 const bytes=Buffer.from(game);a.image.copy(bytes,l.entry-256);
 mkdirSync(new URL('build/caverns/scenarios',root),{recursive:true});
 writeFileSync(new URL('build/caverns/CAVLOAD.COM',root),bytes);
 const record={gameSha256:basic.comSha256,launcherSha256:hash(bytes).toString('hex'),launcherBytes:bytes.length,overlayBytes:a.image.length,availableOverlayBytes:l.resume-l.entry,...l};
 writeFileSync(new URL('build/caverns/scenario-loader.json',root),JSON.stringify(record,null,2)+'\n');return record;
}
export async function packScenarios(){
 const record=await buildLauncher();
 const image=new Uint8Array(read('dist/starter.img')),v=findVolume(parseContainer(image),'A');
 const fs=new CpmVolume(volumePayload(image,v),v.g,{readOnly:false});
 fs.write('CAVLOAD.COM',read('build/caverns/CAVLOAD.COM'));
 writeFileSync(new URL('programs/caverns/CAVLOAD.COM',root),read('build/caverns/CAVLOAD.COM'));
 const files=[];
 for(const name of readdirSync(new URL('test/caverns-scenarios',root)).filter(n=>n.endsWith('.json')).sort()){
  const slot=name.slice(0,-5).toUpperCase();assert.match(slot,/^[A-Z0-9_]{1,8}$/);
  const bytes=encodeScenario(JSON.parse(read('test/caverns-scenarios/'+name)));
  writeFileSync(new URL('build/caverns/scenarios/'+slot+'.CAV',root),bytes);
  fs.write(slot+'.CAV',bytes);writeFileSync(new URL('programs/caverns/'+slot+'.CAV',root),bytes);files.push(slot+'.CAV');
 }
 fs.write('CAVLOAD.TXT',Buffer.from('Caverns development scenarios. Not a public release.\nRun CAVLOAD TROLL, SOUTH, ROPE, CAVE or CANDLE at the TEC-OS prompt.\nQUIT then Y reloads the same scenario; N returns to TEC-OS.\nScenario files match this exact CAVLOAD.COM. Keep exported files outside the emulator.\nThe BASIC game and its original outdoor map are unchanged.\n'),{text:true});
 writeFileSync(new URL('build/caverns/scenarios.img',root),image);
 const manifest={...record,scenarioFiles:files,cardSha256:hash(image).toString('hex')};
 writeFileSync(new URL('build/caverns/scenarios/manifest.json',root),JSON.stringify(manifest,null,2)+'\n');
 return manifest;
}
if(process.argv[1]===new URL(import.meta.url).pathname){
 if(process.argv[2]==='pack')console.log(await packScenarios());
 else if(process.argv[2]==='build')console.log(await buildLauncher());
 else if(process.argv[2]==='write'){const s=JSON.parse(readFileSync(process.argv[3]));writeFileSync(process.argv[4],encodeScenario(s));console.log(process.argv[4]);}
 else throw Error('Use build, pack, or write SCENARIO.json NAME.CAV');
}
