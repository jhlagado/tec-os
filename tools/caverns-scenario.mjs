const root=new URL('../',import.meta.url);
const read=p=>readFileSync(new URL(p,root));
const hash=b=>createHash('sha256').update(b).digest();
const basic=JSON.parse(read('test/caverns-basic.json'));
const game=read('programs/CAVERNS.COM');
assert.equal(hash(game).toString('hex'),basic.comSha256,'launcher must match the qualified BASIC executable');
export const scalarNames=['A%','H%','D%','W%','G%','T%','E%','J%','C0%','F%','U%','R0%','K0%'];
export function encodeScenario(s){
 assert.equal(s.format,'caverns-basic-scenario-2');
 assert.equal(s.gameSha256,basic.comSha256);
 assert.equal(s.objects.length,24);
 if(s.variables['R0%']===1)assert.equal(s.objects[21],28,'secured rope must be on balcony');
 const out=Buffer.alloc(128);Buffer.from('CVB2').copy(out);out[4]=2;hash(game).copy(out,8,0,8);
 const scalars=s.variables;
 const allowed={'A%':v=>v>=1&&v<=54,'H%':v=>v===11,'D%':v=>v===128||v===49,'W%':v=>v===0||v===43,'G%':v=>v===0||v===39,'T%':v=>v===0||v===19,'E%':v=>v===0||v===38,'J%':v=>v===0||v===1,'C0%':v=>v===0||v===1,'F%':v=>v>=0&&v<=32767,'U%':v=>v>=0&&v<=32767,'R0%':v=>v===0||v===1,'K0%':v=>v===0||v===1};
 s.objects.forEach((v,i)=>{assert.ok(Number.isInteger(v)&&v>=-1&&v<=255);if(i>=6)assert.ok(v<=54);out.writeInt16LE(v,16+2*i);});
 scalarNames.forEach((n,i)=>{const v=scalars[n];assert.ok(Number.isInteger(v)&&allowed[n](v),'invalid '+n);out.writeInt16LE(v,64+2*i);});
 assert.match(s.rng,/^[0-9a-fA-F]{8}$/);const rng=Number.parseInt(s.rng,16);assert.notEqual(rng,0);out.writeUInt32LE(rng,90);
 let sum=0;for(let i=0;i<128;i++)if(i!==6&&i!==7)sum+=out[i];out.writeUInt16LE(sum,6);return out;
}
export function layout(){
 function line(n){
  const found=[];
  for(let i=0;i<game.length-9;i++){
   const legacy=game[i]===0x11&&game.readUInt16LE(i+1)===n&&game[i+3]===1&&game.readUInt16LE(i+4)===0&&game[i+6]===0xcd;
   const target=game.readUInt16LE(i+1)-256;
   const compact=game[i]===0xcd&&game.readUInt16LE(i+3)===n&&game.readUInt16LE(i+5)===0&&target>=0&&game.subarray(target,target+10).equals(Buffer.from([0xe3,0x5e,0x23,0x56,0x23,0x4e,0x23,0x46,0x23,0xe3]));
   const restart=game[i]===0xcf&&game.readUInt16LE(i+1)===n;
   if(legacy||compact||restart)found.push(i+256);
  }
  assert.equal(found.length,1,'unique BASIC line '+n);return found[0];
 }
 const seeds=[];for(let i=0;i<game.length-12;i++)if(game[i]===0x21&&game.readUInt16LE(i+1)===0x1234&&game[i+3]===0x22&&game[i+6]===0x21&&game.readUInt16LE(i+7)===0x5a4a&&game[i+9]===0x22){assert.equal(game.readUInt16LE(i+10),game.readUInt16LE(i+4)+2);seeds.push(game.readUInt16LE(i+4));}
 assert.equal(seeds.length,1,'unique qualified runtime RNG initializer');
 return {entry:line(basic.entries?.banner??30),resume:line(basic.entries?.resume??50),rng:seeds[0]};
}
// Read the runtime's own footer pointer, rather than searching text or assuming
// a fixed START address. A development launcher gets its own checked image end.
export function runtimeFooter(bytes){
 assert.equal(bytes[0],0xc3,'runtime entry must jump to START');
 const start=bytes.readUInt16LE(1),at=start-256;
 assert.ok(at>=0&&at+8<=bytes.length,'START within image');
 assert.ok(bytes.subarray(at,at+6).equals(Buffer.from([0x2a,6,0,0xf9,0xed,0x5b])),'checked runtime startup');
 const pointer=bytes.readUInt16LE(at+6),cell=pointer-256;
 assert.ok(cell>=0&&cell+2<=bytes.length,'footer pointer within image');
 const address=bytes.readUInt16LE(cell),offset=address-256;
 assert.ok(offset>=0&&offset+10<=bytes.length,'footer within image');
 assert.equal(bytes.subarray(offset,offset+4).toString(),'BZ01','runtime footer magic');
 assert.equal(bytes.readUInt16LE(offset+4),address+10,'runtime image end');
 assert.ok(bytes.readUInt16LE(offset+6)>=768&&address+10+bytes.readUInt16LE(offset+6)<=65535,'runtime stack reserve');
 assert.equal(bytes.readUInt16LE(offset+8),start,'runtime startup identity');
 return {address,offset,pointer,cell,start};
}
export async function buildLauncher(){
 const footer=runtimeFooter(game);
 const l=layout(),symbols={OBJECTS:basic.symbols[basic.stateSymbols?.['P%()']??'P%()'].address,RNG:l.rng,RESUME:l.resume};
 ['ROOM','BRIDGE','DRAWBR','WALL','GRILLE','DOOR','CRYPT','HUT','LIGHT','FATIGUE','MOVES','ROPE','GATE'].forEach((n,i)=>symbols[n]=basic.symbols[basic.stateSymbols?.[scalarNames[i]]??scalarNames[i]].address);
 [...hash(game).subarray(0,8)].forEach((v,i)=>symbols['HASH'+i]=v);
 writeFileSync(new URL('programs/caverns/load.inc',root),'; Generated by tools/caverns-scenario.mjs; qualified COM-specific addresses.\n'+Object.entries(symbols).map(([n,v])=>n+' EQU $'+v.toString(16).toUpperCase()).join('\n')+'\n');
 const assemble=await tasAssembler(),a=await assemble({root:new URL('programs/caverns',root).pathname,entry:'load.asm',origin:footer.address,phase:'caverns-loader',target:'tecos'});
 const footerAddress=footer.address+a.image.length,imageEnd=footerAddress+10;
 assert.ok(imageEnd+game.readUInt16LE(footer.offset+6)<=65535,'launcher and stack fit address space');
 const bytes=Buffer.alloc(Math.ceil((imageEnd-256)/128)*128,0x1a);
 game.copy(bytes,0,0,footer.offset);a.image.copy(bytes,footer.offset);
 game.copy(bytes,footerAddress-256,footer.offset,footer.offset+10);
 bytes.writeUInt16LE(footerAddress,footer.cell);
 bytes.writeUInt16LE(imageEnd,footerAddress-256+4);
 bytes[l.entry-256]=0xc3;bytes.writeUInt16LE(footer.address,l.entry-256+1);
 runtimeFooter(bytes); // Check the patched startup/footer contract too.
 mkdirSync(new URL('build/caverns/scenarios',root),{recursive:true});
 writeFileSync(new URL('build/caverns/CAVLOAD.COM',root),bytes);
 const record={gameSha256:basic.comSha256,launcherSha256:hash(bytes).toString('hex'),launcherBytes:bytes.length,patchBytes:3,loaderCodeBytes:a.image.length,loaderOrigin:footer.address,footerAddress,imageEnd,...l};
 writeFileSync(new URL('build/caverns/scenario-loader.json',root),JSON.stringify(record,null,2)+'\n');return record;
}
export async function packScenarios(){
 const record=await buildLauncher();
 const image=new Uint8Array(read('dist/starter.img')),v=findVolume(parseContainer(image),'A');
 const fs=new CpmVolume(volumePayload(image,v),v.g,{readOnly:false});
 fs.write('CAVLOAD.COM',read('build/caverns/CAVLOAD.COM'));
 writeFileSync(new URL('programs/caverns/CAVLOAD.COM',root),read('build/caverns/CAVLOAD.COM'));
 const files=[];
 for(const name of readdirSync(new URL('test/caverns-scenarios',root)).filter(n=>n.endsWith('.json')).sort()){
  const slot=name.slice(0,-5).toUpperCase();assert.match(slot,/^[A-Z0-9_]{1,8}$/);
  const bytes=encodeScenario(JSON.parse(read('test/caverns-scenarios/'+name)));
  writeFileSync(new URL('build/caverns/scenarios/'+slot+'.CAV',root),bytes);
  fs.write(slot+'.CAV',bytes);writeFileSync(new URL('programs/caverns/'+slot+'.CAV',root),bytes);files.push(slot+'.CAV');
 }
 fs.write('CAVLOAD.TXT',Buffer.from('Caverns development scenarios. Not a public release.\nRun CAVLOAD CHECK2 (cave entrance), CHECK3 (long tunnel), CHECK4 (bat colony), CHECK5 (temple), CHECK6 (beyond cell), CHECK7 (drains), CHECK8 or VAULT (demon defeated), HUT (four treasures banked), TROLL, SOUTH, ROPE, CAVE or CRYSTAL at the Tecos prompt.\nQUIT then Y reloads the same scenario; N returns to Tecos.\nScenario files match this exact CAVLOAD.COM. Keep exported files outside the emulator.\nAuthor-refined map, reusable rope, reversible crypt and homecoming. Format CVB2.\n'),{text:true});
 writeFileSync(new URL('build/caverns/scenarios.img',root),image);
 const manifest={...record,scenarioFiles:files,cardSha256:hash(image).toString('hex')};
 writeFileSync(new URL('build/caverns/scenarios/manifest.json',root),JSON.stringify(manifest,null,2)+'\n');
 return manifest;
}
if(process.argv[1]===new URL(import.meta.url).pathname){
 if(process.argv[2]==='pack')console.log(await packScenarios());
 else if(process.argv[2]==='build')console.log(await buildLauncher());
 else if(process.argv[2]==='write'){const s=JSON.parse(readFileSync(process.argv[3]));writeFileSync(process.argv[4],encodeScenario(s));console.log(process.argv[4]);}
 else throw Error('Use build, pack, or write SCENARIO.json NAME.CAV');
}
