#!/usr/bin/env node
import { fontPackage } from "./lib/font-package.mjs";
// Build the TEC-1G diagnostics ROM.
//
// Generates diag/gen/config.asm (version, serial delays, stopwatch constants)
// and diag/gen/font.asm, assembles diag/diag.asm, fills the 16 KiB image with
// FFh, stores the 16-bit sum of C000h-FFFDh at FFFEh and writes
// build/diag/diag.rom with its debug map.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { romBackend, tasAssembler, traceRom } from "./lib/tas-rom.mjs";
import { fontSource } from "./lib/font.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = resolve(ROOT, "diag");
const GEN = resolve(SRC, "gen");
const OUT = resolve(ROOT, "build", "diag");
const ROM_START = 0xc000;
const ROM_SIZE = 0x4000;
const CPU_HZ = 4_000_000;
const BAUD = 4800;
const VERSION = { major: 0, minor: 2 };
// The image ID: the first 8 bytes of the SHA-256 of the image with the ID
// and the checksum blank (FFh), stored at ROMID and printed in the report.
const ROMID = 0xfff6;
const ID_LEN = 8;

// T-states from the first speaker edge of the GO beep to the first edge of
// the STOP beep in the CLOCK test, measured on the Debug80 model, whose
// instruction timings are the Z80's own (test/diag.test.mjs checks it).
export const STOPWATCH_T = 240_400_396;

const hex = (value, width = 4) => `$${value.toString(16).toUpperCase().padStart(width, "0")}`;

/** Serial delay counts, as tools/build.mjs derives them for TEC-OS. */
function serialTiming() {
  const bit = CPU_HZ / BAUD;
  const txdly = Math.round((bit - 49) / 16);
  const rxdly = Math.round((bit - 38) / 16);
  const late = 38;
  const rxhalf = Math.round((1.5 * bit - 51 - late / 2) / 16);
  const txstop = Math.round((2 * bit) / 16) + 1;
  for (const [name, n] of Object.entries({ txdly, rxdly, rxhalf, txstop })) {
    if (n < 1 || n > 255) throw new Error(`serial delay ${name}=${n} does not fit a byte`);
  }
  return { txdly, rxdly, rxhalf, txstop, txBit: 49 + 16 * txdly, txStop: 16 * txstop + 11 };
}

function writeGenerated() {
  mkdirSync(GEN, { recursive: true });
  const s = serialTiming();
  const sw10 = STOPWATCH_T * 10;
  if (sw10 >= 2 ** 32) throw new Error("stopwatch interval too long for 32 bits");
  writeFileSync(
    resolve(GEN, "config.asm"),
    `; Generated by tools/diag.mjs. Do not edit.
VERHI   EQU     ${VERSION.major}
VERLO   EQU     ${VERSION.minor}
ROMVER  EQU     ${hex((VERSION.major << 8) | VERSION.minor)}
TXDLY   EQU     ${s.txdly}
TXSTOP  EQU     ${s.txstop}
RXDLY   EQU     ${s.rxdly}
RXHALF  EQU     ${s.rxhalf}
TXBITC  EQU     ${s.txBit}             ; T-states per data bit sent
TXSTOPC EQU     ${s.txStop}            ; T-states for the two stop bits
BITTOL  EQU     ${Math.round(s.txBit / 50)}              ; 2% of a bit
SWTOTL  EQU     ${hex(STOPWATCH_T & 0xffff)}           ; CLOCK interval, T-states
SWTOTH  EQU     ${hex(Math.floor(STOPWATCH_T / 65536))}
SWT10L  EQU     ${hex(sw10 % 65536)}           ; and ten times it
SWT10H  EQU     ${hex(Math.floor(sw10 / 65536))}
`,
  );
  writeFileSync(resolve(GEN, "font.asm"), fontSource(ROOT, "; Generated from format/font5x7.txt by tools/diag.mjs. Do not edit."));
  return s;
}

function check(condition, message) {
  if (!condition) throw new Error(`diagnostics ROM check failed: ${message}`);
}

/** The image ID of a 16 KiB image: what the build stores at ROMID. */
export function imageId(image) {
  const blank = Uint8Array.from(image);
  blank.fill(0xff, ROMID - ROM_START);
  return createHash("sha256").update(blank).digest().subarray(0, ID_LEN);
}

async function assembleDiagAtom() {
  const { assembleAtomProject, materializeAtomGeneration, writeAtomD8 } = await import("atom-z80");
  const result = await assembleAtomProject({ root: SRC, entry: "diag.asm" });
  const d8 = writeAtomD8(result.project, result.generation, { base: ROM_START });
  for (const image of result.generation.images) {
    check(image.address >= ROM_START, `ROM byte emitted at ${hex(image.address)}`);
  }
  const { bytes } = materializeAtomGeneration(result.generation, { base: ROM_START, fill: 0xff });
  traceRom({ backend: "atom", phase: "final", target: "diag.rom", root: SRC });
  return { d8, bytes };
}

export async function buildDiag() {
  const fontNotices = fontPackage(ROOT).notices;
  const backend = romBackend();
  const run = backend === "tas" ? await tasAssembler() : null;
  const serial = writeGenerated();
  const { d8, bytes } = run ? await run({
    root: SRC, entry: "diag.asm", origin: 0x7e00, phase: "final", target: "diag.rom", rom: true,
  }) : await assembleDiagAtom();
  const symbols = new Map(d8.symbols.map((s) => [s.name.toUpperCase(), s.address ?? s.value]));
  const at = (name) => {
    const v = symbols.get(name);
    if (typeof v !== "number") throw new Error(`symbol ${name} missing from the map`);
    return v;
  };
  check(at("RESET") === 0xc000, "RESET must be at C000h");
  check(at("INT38") === 0xc038, "INT38 must be at C038h");
  check(at("NMIROM") === 0xc066, "NMIROM must be at C066h");
  check(at("COLD") < 0xc800, "cold boot entry must be inside the overlay window");
  check(at("START") < 0xc800, "the RAM check must finish inside the overlay window");
  check(at("CODEEND") <= ROMID, `code ends at ${hex(at("CODEEND"))}, over the image ID`);
  check(at("ROMID") === ROMID, "ROMID must match tools/diag.mjs");
  check(at("VARSEND") <= 0x7f00, "variables overrun the stack page");
  check(at("NMITPE") - at("NMITPL") <= 0x38, "NMI handler too long for page zero");
  const rom = new Uint8Array(ROM_SIZE).fill(0xff);
  rom.set(bytes);
  rom.set(imageId(rom), ROMID - ROM_START);
  let sum = 0;
  for (let i = 0; i < ROM_SIZE - 2; i += 1) sum = (sum + rom[i]) & 0xffff;
  rom[ROM_SIZE - 2] = sum & 0xff;
  rom[ROM_SIZE - 1] = sum >> 8;
  mkdirSync(OUT, { recursive: true });
  writeFileSync(resolve(OUT, "diag.rom"), rom);
  writeFileSync(resolve(OUT, "FONT-NOTICES.txt"), fontNotices);
  writeFileSync(resolve(OUT, "diag.d8.json"), JSON.stringify(d8, null, 2));
  const info = {
    id: Buffer.from(imageId(rom)).toString("hex").toUpperCase(),
    sha256: createHash("sha256").update(rom).digest("hex"),
    checksum: sum,
    used: at("CODEEND") - ROM_START,
    free: ROMID - at("CODEEND"),
    serial,
  };
  writeFileSync(resolve(OUT, "diag.json"), JSON.stringify(info, null, 2) + "\n");
  return info;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const info = await buildDiag();
    console.log(
      `diag: ROM ${info.used}/${ROM_SIZE} bytes, ${info.free} free, image ${info.id}, checksum ${hex(info.checksum)}`,
    );
  } catch (error) {
    console.error(error.diagnostic ? JSON.stringify(error.diagnostic) : "", error.message);
    process.exit(1);
  }
}
