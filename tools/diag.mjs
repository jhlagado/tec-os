#!/usr/bin/env node
// Build the TEC-1G diagnostics, a RAM program that MON3 loads and runs at
// 4000h (docs/diagnostics.md).
//
// Generates diag/gen/config.asm (version, TEC-OS's serial delays, the
// container format's fields) and diag/gen/fmt.asm (the magic and the
// geometry table), assembles diag/diag.asm with TAS, checks the memory
// layout, stores the image ID and writes build/diag/: DIAG.BIN, DIAG.HEX,
// diag.d8.json (the symbol map) and diag.json (size, ID and SHA-256).

import { mkdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tasAssembler } from "./lib/tas-rom.mjs";
import { format } from "./lib/format.mjs";
import { serialTiming } from "./build.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GEN = resolve(ROOT, "diag", "gen");
const OUT = resolve(ROOT, "build", "diag");
export const VERSION = { major: 1, minor: 0 };
export const LOAD = 0x4000; // where MON3's GO starts it
const VARS = 0x1000; // variables and buffers: 1000h-3FFFh
const CODE_TOP = 0x8000; // code and tables: 4000h-7FFFh, maybe protected
const ID_LEN = 8;
// Card sizes as sold, in decimal bytes, for SD4's capacity check.
const CLASSES = [
  ["128MB", 128e6], ["256MB", 256e6], ["512MB", 512e6],
  ...[1, 2, 4, 8, 16, 32, 64, 128, 256, 512].map((g) => [`${g}GB`, g * 1e9]),
  ["1TB", 1024e9],
];
const w16 = (v) => "$" + v.toString(16).toUpperCase().padStart(4, "0");
const dw32 = (v) => `${w16(v % 65536)},${w16(Math.floor(v / 65536))}`;

const hex = (value, width = 4) => `$${value.toString(16).toUpperCase().padStart(width, "0")}`;

function writeGenerated() {
  mkdirSync(GEN, { recursive: true });
  const s = serialTiming();
  const h = format.header;
  const d = format.descriptor;
  const equ = (name, value) => `${name.padEnd(10)}EQU   ${value}`;
  const lines = [
    "; Generated by tools/diag.mjs. Do not edit.",
    "",
    equ("VERHI", VERSION.major),
    equ("VERLO", VERSION.minor),
    equ("TXDLY", s.txdly),
    equ("TXSTOP", s.txstop),
    "",
    "; From format/format.json, as the ROM's",
    "; src/gen/format.asm has them.",
    "",
    equ("FMTMAJ", format.formatVersion.major),
    equ("HDRSZ", h.bytes),
    equ("DSCSZ", d.bytes),
    equ("MAXVOL", h.maxVolumes),
    equ("MAXVOL0", h.maxVolumesMinor0),
    equ("DSCBLK0", h.descriptorsInBlock0),
    equ("HMAJOR", h.fields.major.offset),
    equ("HMINOR", h.fields.minor.offset),
    equ("HHDRSZ", h.fields.headerBytes.offset),
    equ("HDSCSZ", h.fields.descriptorBytes.offset),
    equ("HCOUNT", h.fields.volumeCount.offset),
    equ("HBLOCKS", h.fields.containerBlocks.offset),
    equ("HCKSUM", h.fields.checksum.offset),
    equ("HDRIVES", h.fields.drives.offset),
    equ("HTSUM", h.fields.tableSum.offset),
    equ("DVOLID", d.fields.volumeId.offset),
    equ("DSTART", d.fields.startBlock.offset),
    equ("DLEN", d.fields.lengthBlocks.offset),
    equ("DGEOM", d.fields.geometry.offset),
    equ("DFLAGS", d.fields.flags.offset),
    equ("DMOUNT", d.fields.mount.offset),
    equ("DFREAD", d.flags.readOnly),
    equ("DUNMNT", d.unmounted),
    equ("ALIGNB", d.startAlignBlocks),
    equ("MAXDRV", format.maxDrives),
  ];
  if (h.descriptorsPerBlock !== 16) throw new Error("SD7 assumes 16 descriptors a table block");
  writeFileSync(resolve(GEN, "config.asm"), lines.join("\n") + "\n");
  const geo = format.geometries.map((g) => `  DB ${g.id}\n  DW ${g.payloadBlocks}`);
  writeFileSync(
    resolve(GEN, "fmt.asm"),
    [
      "; Generated by tools/diag.mjs from",
      "; format/format.json. Do not edit.",
      "",
      `MAGIC:    DB    "${h.magic}"`,
      "",
      "; Each geometry's id and payload length;",
      "; id 0 ends the table.",
      "",
      "GEOTAB:",
      ...geo,
      "  DB 0",
      "",
      "; SD4's capacity classes: the blocks of",
      "; a card sold as each size (decimal",
      "; bytes), 90% of that, and its name. A",
      "; zero class ends the table.",
      "",
      "CLSTAB:",
      ...CLASSES.flatMap(([, bytes], i) => {
        const blocks = bytes / 512;
        const warn = Math.ceil(blocks * 0.9);
        return [`  DW ${dw32(blocks)}`, `  DW ${dw32(warn)},CLN${i}`];
      }),
      "  DW 0,0",
      ...CLASSES.map(([name], i) => `CLN${i}:`.padEnd(10) + `DB    "${name}",0`),
      "",
    ].join("\n"),
  );
  return s;
}

function check(condition, message) {
  if (!condition) throw new Error(`diagnostics build check failed: ${message}`);
}

/** The image ID: the first 8 bytes of the SHA-256 of the image with the ID zero. */
export function imageId(image, at) {
  const blank = Uint8Array.from(image);
  blank.fill(0, at, at + ID_LEN);
  return createHash("sha256").update(blank).digest().subarray(0, ID_LEN);
}

/** Intel HEX for bytes at `base`: 16-byte data records and the end record. */
export function intelHex(bytes, base) {
  const lines = [];
  for (let at = 0; at < bytes.length; at += 16) {
    const chunk = bytes.subarray(at, at + 16);
    const address = base + at;
    const record = [chunk.length, address >> 8, address & 0xff, 0, ...chunk];
    const sum = (0x100 - (record.reduce((a, b) => a + b, 0) & 0xff)) & 0xff;
    lines.push(":" + [...record, sum].map((b) => b.toString(16).toUpperCase().padStart(2, "0")).join(""));
  }
  lines.push(":00000001FF");
  return lines.join("\r\n") + "\r\n";
}

export async function buildDiag() {
  const serial = writeGenerated();
  const run = await tasAssembler();
  const r = await run({ root: ROOT, entry: "diag/diag.asm", origin: VARS, phase: "final", target: "DIAG.BIN", flat: true });
  const at = (name) => {
    const v = r.globals.get(name);
    if (!v) throw new Error(`symbol ${name} missing from the map`);
    return v.value;
  };
  check(at("VARS") === VARS, "variables must start at 1000h");
  check(at("VARSEND") <= LOAD, `variables end at ${hex(at("VARSEND"))}, past 3FFFh`);
  check(at("START") === LOAD, "START must be at 4000h");
  check(at("PROGEND") === r.end, "PROGEND must end the image");
  check(at("PROGEND") < CODE_TOP - 1, `code and tables end at ${hex(at("PROGEND"))}, past 7FFEh`);
  check(r.image.subarray(0, LOAD - VARS).every((b) => b === 0), "bytes below 4000h: the variables must be reserved only");
  const image = Uint8Array.from(r.image.subarray(LOAD - VARS));
  const idAt = at("IMGID") - LOAD;
  check(image.subarray(idAt, idAt + ID_LEN).every((b) => b === 0), "IMGID must be eight zero bytes");
  const id = imageId(image, idAt);
  image.set(id, idAt);
  const symbols = [...r.globals]
    .map(([name, { kind, value }]) => (kind === "label" ? { name, kind, address: value } : { name, kind, value }))
    .sort((a, b) => (a.address ?? a.value) - (b.address ?? b.value) || (a.name < b.name ? -1 : 1));
  const d8 = {
    format: "d8-debug-map",
    version: 1,
    arch: "z80",
    addressWidth: 16,
    endianness: "little",
    segments: [{ start: LOAD, end: at("PROGEND") }],
    symbols,
    generator: { name: "tas", tool: "tas", inputs: { entry: "diag/diag.asm" }, entryAddress: LOAD },
  };
  mkdirSync(OUT, { recursive: true });
  writeFileSync(resolve(OUT, "DIAG.BIN"), image);
  writeFileSync(resolve(OUT, "DIAG.HEX"), intelHex(image, LOAD));
  writeFileSync(resolve(OUT, "diag.d8.json"), JSON.stringify(d8, null, 2) + "\n");
  const info = {
    version: `${VERSION.major}.${VERSION.minor}`,
    id: Buffer.from(id).toString("hex").toUpperCase(),
    sha256: createHash("sha256").update(image).digest("hex"),
    load: hex(LOAD),
    bytes: image.length,
    end: hex(at("PROGEND")),
    vars: hex(VARS),
    varsEnd: hex(at("VARSEND")),
    varBytes: at("VARSEND") - VARS,
    serial: { txdly: serial.txdly, txstop: serial.txstop, txBitCycles: serial.txBitCycles },
  };
  writeFileSync(resolve(OUT, "diag.json"), JSON.stringify(info, null, 2) + "\n");
  return { ...info, image, symbols: new Map(symbols.map((s) => [s.name, s.address ?? s.value])) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const info = await buildDiag();
    console.log(
      `diag: ${info.bytes} bytes at 4000h-${info.end.slice(1)}h, variables 1000h-${info.varsEnd.slice(1)}h, image ${info.id}, sha256 ${info.sha256.slice(0, 16)}`,
    );
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
